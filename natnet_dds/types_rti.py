"""NatNet DDS types for RTI Connext DDS (rti.connext Python API).

Mirrors idl/NatNetDDS.idl exactly (same type names, member order and
extensibility) so samples interoperate with code generated by rtiddsgen
and with other DDS vendors.
"""
import typing
from dataclasses import field

import rti.idl as idl


def _final(name):
    return [idl.type_name(name), idl.final]


@idl.struct(type_annotations=_final("NatNet::Vector3"))
class Vector3:
    x: idl.float32 = 0.0
    y: idl.float32 = 0.0
    z: idl.float32 = 0.0


@idl.struct(type_annotations=_final("NatNet::Quaternion"))
class Quaternion:
    x: idl.float32 = 0.0
    y: idl.float32 = 0.0
    z: idl.float32 = 0.0
    w: idl.float32 = 1.0


@idl.struct(type_annotations=_final("NatNet::RigidBodyPose"))
class RigidBodyPose:
    id: idl.int32 = 0
    name: str = ""
    position: Vector3 = field(default_factory=Vector3)
    orientation: Quaternion = field(default_factory=Quaternion)
    mean_error: idl.float32 = 0.0
    tracking_valid: bool = False


@idl.struct(type_annotations=_final("NatNet::Skeleton"))
class Skeleton:
    id: idl.int32 = 0
    name: str = ""
    bones: typing.Sequence[RigidBodyPose] = field(default_factory=list)


@idl.struct(type_annotations=_final("NatNet::MarkerSet"))
class MarkerSet:
    name: str = ""
    markers: typing.Sequence[Vector3] = field(default_factory=list)


@idl.struct(type_annotations=_final("NatNet::LabeledMarker"))
class LabeledMarker:
    id: idl.int32 = 0
    model_id: idl.int32 = 0
    marker_id: idl.int32 = 0
    position: Vector3 = field(default_factory=Vector3)
    size: idl.float32 = 0.0
    occluded: bool = False
    residual: idl.float32 = 0.0


@idl.struct(type_annotations=_final("NatNet::FrameOfMocapData"))
class FrameOfMocapData:
    frame_number: idl.int32 = 0
    timestamp: float = 0.0
    timecode: idl.uint32 = 0
    timecode_sub: idl.uint32 = 0
    stamp_camera_mid_exposure: idl.int64 = 0
    stamp_data_received: idl.int64 = 0
    stamp_transmit: idl.int64 = 0
    is_recording: bool = False
    tracked_models_changed: bool = False
    rigid_bodies: typing.Sequence[RigidBodyPose] = field(default_factory=list)
    skeletons: typing.Sequence[Skeleton] = field(default_factory=list)
    labeled_markers: typing.Sequence[LabeledMarker] = field(default_factory=list)
    marker_sets: typing.Sequence[MarkerSet] = field(default_factory=list)


@idl.struct(type_annotations=_final("NatNet::RigidBody"),
            member_annotations={"id": [idl.key]})
class RigidBody:
    id: idl.int32 = 0
    name: str = ""
    frame_number: idl.int32 = 0
    timestamp: float = 0.0
    position: Vector3 = field(default_factory=Vector3)
    orientation: Quaternion = field(default_factory=Quaternion)
    mean_error: idl.float32 = 0.0
    tracking_valid: bool = False
